import { IntrinsicFunctionResolver } from '../../../src/deployment/intrinsic-function-resolver.js';
import type { ResolverContext } from '../../../src/deployment/intrinsic-function-resolver.js';
import {
  producerLookupOver,
  type ProducerLookup,
} from '../../../src/deployment/intrinsic-resolver/cdk-cross-account-ref.js';
import { isMarkedNonRetryable } from '../../../src/deployment/retryable-errors.js';
import { clearCrossAccountCredentialsCache } from '../../../src/utils/role-arn.js';
import { clearBucketRegionCache } from '../../../src/utils/aws-region-resolver.js';
import { CrossAccountSecretRefusalError } from '../../../src/utils/error-handler.js';
import type { S3StateBackend } from '../../../src/state/s3-state-backend.js';
import type { StateOutputReadEntry } from '../../../src/types/state.js';
import {
  CONSUMER_ACCOUNT,
  PRODUCER_ACCOUNT,
  SECOND_CONSUMER_ACCOUNT,
  synthesizeCrossAccountApp,
  type SynthesizedApp,
} from './cdk-cross-account-fixture.js';

const LOOKUP_ROLE_ARN = `arn:aws:iam::${PRODUCER_ACCOUNT}:role/cdk-hnb659fds-lookup-role-${PRODUCER_ACCOUNT}-us-east-1`;

let generated: SynthesizedApp;
let partitionLiterals: SynthesizedApp;
let userFormatArn: SynthesizedApp;

beforeAll(() => {
  generated = synthesizeCrossAccountApp('generated');
  partitionLiterals = synthesizeCrossAccountApp('generated-partition-literals');
  userFormatArn = synthesizeCrossAccountApp('user-format-arn');
}, 120_000);

function context(overrides: Partial<ResolverContext> = {}): ResolverContext {
  return { template: { Resources: {} }, resources: {}, stackName: 'Consumer', ...overrides };
}

function primeAssumeRole(): void {
  mockStsSend.mockResolvedValueOnce({
    Credentials: {
      AccessKeyId: 'ASIA-lookup',
      SecretAccessKey: 'lookup-secret',
      SessionToken: 'lookup-token',
      Expiration: new Date('2099-01-01T00:00:00Z'),
    },
  });
}

function primeProducerState(outputs: Record<string, unknown>, bucketLocation = true): void {
  // The bucket's region is cached per process, so only a first read asks for it.
  if (bucketLocation) mockS3Send.mockResolvedValueOnce({ LocationConstraint: 'us-east-1' });
  mockS3Send.mockResolvedValueOnce({
    Body: {
      transformToString: async () =>
        JSON.stringify({
          version: 4,
          stackName: 'Producer',
          region: 'us-east-1',
          resources: {},
          outputs,
          lastModified: 1700000000000,
        }),
    },
    ETag: '"etag"',
  });
}

async function refusalOf(promise: Promise<unknown>): Promise<Error> {
  try {
    await promise;
  } catch (error) {
    return error as Error;
  }
  throw new Error('expected a refusal');
}

describe('Fn::GetStackOutput generated by aws-cdk-lib across accounts', () => {
  beforeEach(() => {
    mockStsSend.mockReset();
    mockS3Send.mockReset();
    cfnMockSend.mockReset();
    clearCrossAccountCredentialsCache();
    clearBucketRegionCache();
  });

  it('reads through the producer lookup role, never the generated role, and records no output read', async () => {
    primeAssumeRole();
    primeProducerState({ [generated.reference['OutputName'] as string]: 'arn:aws:sns:topic' });
    const recordedOutputReads: StateOutputReadEntry[] = [];
    const resolver = new IntrinsicFunctionResolver('us-east-1', {
      producerLookup: producerLookupOver(generated.stacks),
    });
    const value = await resolver.resolve(
      { 'Fn::GetStackOutput': generated.reference },
      context({ recordedOutputReads })
    );
    expect(value).toBe('arn:aws:sns:topic');
    expect(mockStsSend).toHaveBeenCalledTimes(1);
    expect(mockStsSend.mock.calls[0][0].input.RoleArn).toBe(LOOKUP_ROLE_ARN);
    const s3Inputs = mockS3Send.mock.calls.map((call) => call[0].input);
    expect(s3Inputs.map((i) => i.Bucket)).toEqual([
      `cdkd-state-${PRODUCER_ACCOUNT}`,
      `cdkd-state-${PRODUCER_ACCOUNT}`,
    ]);
    expect(s3Inputs[1].Key).toBe('cdkd/Producer/us-east-1/state.json');
    expect(recordedOutputReads).toEqual([]);
    expect(cfnMockSend).not.toHaveBeenCalled();
  });

  it('reads the partition-literal form through the lookup role too', async () => {
    primeAssumeRole();
    primeProducerState({ [partitionLiterals.reference['OutputName'] as string]: 'v' });
    const resolver = new IntrinsicFunctionResolver('us-east-1', {
      producerLookup: producerLookupOver(partitionLiterals.stacks),
    });
    await expect(
      resolver.resolve({ 'Fn::GetStackOutput': partitionLiterals.reference }, context())
    ).resolves.toBe('v');
    expect(mockStsSend.mock.calls[0][0].input.RoleArn).toBe(LOOKUP_ROLE_ARN);
  });

  it('keeps the cross-account secret refusal', async () => {
    primeAssumeRole();
    primeProducerState({
      [generated.reference['OutputName'] as string]: '{{resolve:secretsmanager:db-password}}',
    });
    const resolver = new IntrinsicFunctionResolver('us-east-1', {
      producerLookup: producerLookupOver(generated.stacks),
    });
    const error = await refusalOf(
      resolver.resolve({ 'Fn::GetStackOutput': generated.reference }, context())
    );
    expect(error).toBeInstanceOf(CrossAccountSecretRefusalError);
    expect(error.message).toContain(
      `, read through the producer account's CDK lookup role ${LOOKUP_ROLE_ARN})`
    );
  });

  it('keeps the secret refusal text unchanged for a user literal RoleArn', async () => {
    const userRole = `arn:aws:iam::${PRODUCER_ACCOUNT}:role/cdkd-state-reader`;
    primeAssumeRole();
    primeProducerState({ TopicArn: '{{resolve:secretsmanager:db-password}}' });
    const resolver = new IntrinsicFunctionResolver('us-east-1', {
      producerLookup: producerLookupOver(userFormatArn.stacks),
    });
    const error = await refusalOf(
      resolver.resolve(
        {
          'Fn::GetStackOutput': {
            StackName: 'Producer',
            OutputName: 'TopicArn',
            Region: 'us-east-1',
            RoleArn: userRole,
          },
        },
        context()
      )
    );
    expect(error).toBeInstanceOf(CrossAccountSecretRefusalError);
    expect(error.message).toContain(`CROSS-ACCOUNT reference (RoleArn ${userRole}). cdkd will`);
  });

  it('refuses with both remedies when the lookup role cannot be assumed, and never falls back', async () => {
    mockStsSend.mockRejectedValueOnce(
      Object.assign(new Error('User is not authorized to perform: sts:AssumeRole\u001b[2K'), {
        name: 'AccessDenied',
      })
    );
    const resolver = new IntrinsicFunctionResolver('us-east-1', {
      producerLookup: producerLookupOver(generated.stacks),
      consumerAccount: CONSUMER_ACCOUNT,
    });
    const error = await refusalOf(
      resolver.resolve({ 'Fn::GetStackOutput': generated.reference }, context())
    );
    expect(isMarkedNonRetryable(error)).toBe(true);
    // The AWS failure rides along as the cause.
    expect((error.cause as Error | undefined)?.message).toMatch(/^AssumeRole into /);
    const roleName = (generated.reference['RoleArn'] as { 'Fn::Join': [string, string[]] })['Fn::Join'][1][2]!
      .split('/')
      .pop();
    for (const needle of [
      `of stack Producer (region us-east-1, account ${PRODUCER_ACCOUNT}) for stack Consumer`,
      `Its RoleArn names ${roleName}`,
      `assuming the lookup role ${LOOKUP_ROLE_ARN}`,
      'User is not authorized to perform: sts:AssumeRole',
      `cdk bootstrap --trust-for-lookup ${CONSUMER_ACCOUNT}`,
      `cdkd-state-${PRODUCER_ACCOUNT}`,
      'https://cdkd.dev/cross-stack-references/#reading-from-another-account',
    ]) {
      expect(error.message).toContain(needle);
    }
    expect(error.message).not.toContain('\u001b');
    // The real role-arn.ts wrapper (`AssumeRole into ... failed: ... If this is
    // a trust-policy issue, ...`) is the cause; only AWS's innermost words are
    // quoted, and the sentence join has exactly one period.
    expect((error.cause as Error).message).toContain('If this is a trust-policy issue');
    expect(error.message).toContain('was denied: AccessDenied: User is not authorized');
    expect(error.message).not.toContain('trust-policy issue');
    expect(error.message).not.toContain('AssumeRole into');
    expect(error.message).not.toMatch(/\.\s*\./);
    expect(error.message).toMatch(/sts:AssumeRole[^.]*\. Fix it one of two ways: \(1\) in account /);
    expect(mockStsSend).toHaveBeenCalledTimes(1);
    expect(mockS3Send).not.toHaveBeenCalled();
    expect(cfnMockSend).not.toHaveBeenCalled();
  });

  it('refuses a denied state read through the lookup role', async () => {
    primeAssumeRole();
    mockS3Send.mockResolvedValueOnce({ LocationConstraint: 'us-east-1' });
    mockS3Send.mockRejectedValueOnce(Object.assign(new Error('Access Denied'), { name: 'AccessDenied' }));
    const resolver = new IntrinsicFunctionResolver('us-east-1', {
      producerLookup: producerLookupOver(generated.stacks),
    });
    const error = await refusalOf(
      resolver.resolve({ 'Fn::GetStackOutput': generated.reference }, context())
    );
    expect(error.message).toContain('Access Denied');
    expect(error.message).toContain('--trust-for-lookup');
    expect(isMarkedNonRetryable(error)).toBe(true);
    expect(error.cause).toBeInstanceOf(Error);
  });

  it.each([
    ['a throttle', Object.assign(new Error('Rate exceeded'), { name: 'ThrottlingException' })],
    ['a 5xx', Object.assign(new Error('We encountered an internal error'), {
      name: 'InternalError',
      $metadata: { httpStatusCode: 500 },
    })],
    ['a missing bucket', Object.assign(new Error('The specified bucket does not exist'), {
      name: 'NoSuchBucket',
      $metadata: { httpStatusCode: 404 },
    })],
  ])('leaves %s on the ordinary path, not the lookup-role refusal', async (_label, failure) => {
    primeAssumeRole();
    mockS3Send.mockResolvedValueOnce({ LocationConstraint: 'us-east-1' });
    mockS3Send.mockRejectedValue(failure);
    const resolver = new IntrinsicFunctionResolver('us-east-1', {
      producerLookup: producerLookupOver(generated.stacks),
    });
    const error = await refusalOf(
      resolver.resolve({ 'Fn::GetStackOutput': generated.reference }, context())
    );
    expect(error.message).toMatch(/^Failed to get state for stack Producer/);
    expect(error.message).not.toContain('--trust-for-lookup');
  });

  it('leaves a malformed producer record on the ordinary path', async () => {
    primeAssumeRole();
    mockS3Send.mockResolvedValueOnce({ LocationConstraint: 'us-east-1' });
    mockS3Send.mockResolvedValueOnce({ Body: undefined, ETag: '"e"' });
    const resolver = new IntrinsicFunctionResolver('us-east-1', {
      producerLookup: producerLookupOver(generated.stacks),
    });
    const error = await refusalOf(
      resolver.resolve({ 'Fn::GetStackOutput': generated.reference }, context())
    );
    expect(error.message).not.toContain('--trust-for-lookup');
  });

  it('names the consumer stack own account, not every account the shared role trusts', async () => {
    const app = synthesizeCrossAccountApp('two-consumers');
    const second = app.stacks.find((st) => st.stackName === 'ConsumerB')!;
    const reference = JSON.parse(JSON.stringify(second.template.Resources)).Queue.Properties
      .QueueName['Fn::GetStackOutput'] as Record<string, unknown>;
    mockStsSend.mockRejectedValueOnce(Object.assign(new Error('denied'), { name: 'AccessDenied' }));
    const resolver = new IntrinsicFunctionResolver('us-east-1', {
      producerLookup: producerLookupOver(app.stacks),
      consumerAccount: SECOND_CONSUMER_ACCOUNT,
    });
    const error = await refusalOf(
      resolver.resolve({ 'Fn::GetStackOutput': reference }, context({ stackName: 'ConsumerB' }))
    );
    expect(error.message).toContain(`--trust-for-lookup ${SECOND_CONSUMER_ACCOUNT}'`);
    expect(error.message).not.toContain(CONSUMER_ACCOUNT);
  }, 60_000);

  it('names the lookup role in the not-found message', async () => {
    primeAssumeRole();
    mockS3Send.mockResolvedValueOnce({ LocationConstraint: 'us-east-1' });
    mockS3Send.mockRejectedValueOnce(
      Object.assign(new Error('The specified key does not exist.'), {
        name: 'NoSuchKey',
        $metadata: { httpStatusCode: 404 },
      })
    );
    mockS3Send.mockRejectedValue(
      Object.assign(new Error('The specified key does not exist.'), {
        name: 'NoSuchKey',
        $metadata: { httpStatusCode: 404 },
      })
    );
    const resolver = new IntrinsicFunctionResolver('us-east-1', {
      producerLookup: producerLookupOver(generated.stacks),
    });
    const error = await refusalOf(
      resolver.resolve({ 'Fn::GetStackOutput': generated.reference }, context())
    );
    expect(error.message).toContain(`(cross-account via ${LOOKUP_ROLE_ARN})`);
  });

  it('refuses without any AWS call when the producer names no lookup role', async () => {
    const stacks = generated.stacks.map((s) =>
      s.stackName === 'Producer' ? { ...s, lookupRoleArn: undefined } : s
    );
    const resolver = new IntrinsicFunctionResolver('us-east-1', {
      producerLookup: producerLookupOver(stacks),
    });
    const error = await refusalOf(
      resolver.resolve({ 'Fn::GetStackOutput': generated.reference }, context())
    );
    expect(error.message).toContain('names no CDK lookup role');
    expect(error.message).toContain(
      '(1) synthesize stack Producer with a stack synthesizer that names a lookup role'
    );
    expect(error.message).toContain('cdk.Fn.getStackOutput(');
    expect(isMarkedNonRetryable(error)).toBe(true);
    expect(mockStsSend).not.toHaveBeenCalled();
  });

  it('refuses without any AWS call when the producer is not in the assembly', async () => {
    const resolver = new IntrinsicFunctionResolver('us-east-1', {
      producerLookup: producerLookupOver([generated.consumer]),
    });
    const error = await refusalOf(
      resolver.resolve({ 'Fn::GetStackOutput': generated.reference }, context())
    );
    expect(error.message).toContain("not in this app's cloud assembly");
    expect(mockStsSend).not.toHaveBeenCalled();
  });

  it('keeps today’s refusal for a user formatArn reader role and for an unwired command', async () => {
    for (const lookup of [producerLookupOver(userFormatArn.stacks), undefined]) {
      const resolver = new IntrinsicFunctionResolver('us-east-1', {
        ...(lookup && { producerLookup: lookup }),
      });
      const error = await refusalOf(
        resolver.resolve({ 'Fn::GetStackOutput': userFormatArn.reference }, context())
      );
      expect(error.message).toMatch(/^Fn::GetStackOutput: RoleArn must be a literal string in the template/);
    }
    const unwired = new IntrinsicFunctionResolver('us-east-1');
    await expect(
      unwired.resolve({ 'Fn::GetStackOutput': generated.reference }, context())
    ).rejects.toThrow(/RoleArn must be a literal string/);
    expect(mockStsSend).not.toHaveBeenCalled();
  });

  it('assumes a user literal RoleArn as written', async () => {
    const userRole = `arn:aws:iam::${PRODUCER_ACCOUNT}:role/cdkd-state-reader`;
    primeAssumeRole();
    primeProducerState({ TopicArn: 'v' });
    const resolver = new IntrinsicFunctionResolver('us-east-1', {
      producerLookup: producerLookupOver(userFormatArn.stacks),
    });
    await expect(
      resolver.resolve(
        {
          'Fn::GetStackOutput': {
            StackName: 'Producer',
            OutputName: 'TopicArn',
            Region: 'us-east-1',
            RoleArn: userRole,
          },
        },
        context()
      )
    ).resolves.toBe('v');
    expect(mockStsSend.mock.calls[0][0].input.RoleArn).toBe(userRole);
  });

  it('classifies a producer once per resolver instance', async () => {
    const lookup = vi.fn<ProducerLookup>(producerLookupOver(generated.stacks));
    const resolver = new IntrinsicFunctionResolver('us-east-1', { producerLookup: lookup });
    for (let i = 0; i < 2; i++) {
      if (i === 0) primeAssumeRole();
      primeProducerState({ [generated.reference['OutputName'] as string]: 'v' }, i === 0);
      await resolver.resolve({ 'Fn::GetStackOutput': generated.reference }, context());
    }
    expect(lookup).toHaveBeenCalledTimes(1);
    // The memo is keyed by producer stack name too: another producer name is
    // classified afresh (and, absent from the assembly, refused).
    await expect(
      resolver.resolve(
        { 'Fn::GetStackOutput': { ...generated.reference, StackName: 'OtherProducer' } },
        context()
      )
    ).rejects.toThrow(/not in this app's cloud assembly/);
    expect(lookup).toHaveBeenCalledTimes(2);
  });

  it('a reference without a RoleArn never consults the producer lookup', async () => {
    const lookup = vi.fn<ProducerLookup>(() => {
      throw new Error('the producer lookup must not run');
    });
    const getState = vi.fn().mockResolvedValue({
      state: {
        version: 4,
        stackName: 'Producer',
        region: 'us-east-1',
        resources: {},
        outputs: { Out: 'same-account' },
        lastModified: 1,
      },
      etag: '"e"',
    });
    const resolver = new IntrinsicFunctionResolver('us-east-1', { producerLookup: lookup });
    await expect(
      resolver.resolve(
        { 'Fn::GetStackOutput': { StackName: 'Producer', OutputName: 'Out', Region: 'eu-west-1' } },
        context({ stateBackend: { getState } as unknown as S3StateBackend })
      )
    ).resolves.toBe('same-account');
    expect(lookup).not.toHaveBeenCalled();
    expect(mockStsSend).not.toHaveBeenCalled();
  });
});
